export function filterRequests(requests, query, type) {
  const search = query.trim().toLocaleLowerCase('ru')
  return requests.filter(request =>
    (type === 'all' || request.type === type) &&
    `${request.title} ${request.id}`.toLocaleLowerCase('ru').includes(search),
  )
}

export function confirmRequest(confirmed, id) {
  return confirmed[id] ? confirmed : { ...confirmed, [id]: true }
}
